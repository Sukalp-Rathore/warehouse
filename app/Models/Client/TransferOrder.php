<?php

namespace App\Models\Client;

use MongoDB\Laravel\Eloquent\Model;
use Illuminate\Database\Eloquent\Factories\HasFactory;

class TransferOrder extends Model
{
    use HasFactory;

    protected $connection = 'tenant';
    protected $collection = 'transfer_orders';

    protected $fillable = [
        'to_number',
        'from_bin_id',
        'to_bin_id',
        'item_id',
        'item_code',
        'batch_id',
        'quantity',
        'status',
        'priority',
        'auto_generated',
        'reason',
        'assigned_to',
        'approved_by',
        'approved_at',
        'started_at',
        'completed_at',
        'notes',
        'created_by'
    ];

    protected $casts = [
        'quantity' => 'decimal:2',
        'auto_generated' => 'boolean',
        'approved_at' => 'datetime',
        'started_at' => 'datetime',
        'completed_at' => 'datetime',
    ];

    protected $dates = [
        'approved_at',
        'started_at',
        'completed_at',
        'created_at',
        'updated_at'
    ];

    /**
     * Get the source bin
     */
    public function fromBin()
    {
        return $this->belongsTo(Bin::class, 'from_bin_id');
    }

    /**
     * Get the destination bin
     */
    public function toBin()
    {
        return $this->belongsTo(Bin::class, 'to_bin_id');
    }

    /**
     * Get the item
     */
    public function item()
    {
        return $this->belongsTo(Item::class, 'item_id');
    }

    /**
     * Get the batch
     */
    public function batch()
    {
        return $this->belongsTo(Batch::class, 'batch_id');
    }

    /**
     * Get the assigned operator
     */
    public function assignedTo()
    {
        return $this->belongsTo(User::class, 'assigned_to');
    }

    /**
     * Get the approver
     */
    public function approvedBy()
    {
        return $this->belongsTo(User::class, 'approved_by');
    }

    /**
     * Get the creator
     */
    public function createdBy()
    {
        return $this->belongsTo(User::class, 'created_by');
    }

    /**
     * Approve transfer order
     */
    public function approve($userId)
    {
        $this->update([
            'status' => 'approved',
            'approved_by' => $userId,
            'approved_at' => now(),
        ]);
    }

    /**
     * Assign to operator
     */
    public function assign($userId)
    {
        $this->update([
            'assigned_to' => $userId,
        ]);
    }

    /**
     * Start execution
     */
    public function start()
    {
        $this->update([
            'status' => 'in_progress',
            'started_at' => now(),
        ]);
    }

    /**
     * Complete transfer order
     */
    public function complete()
    {
        $this->update([
            'status' => 'completed',
            'completed_at' => now(),
        ]);
    }

    /**
     * Cancel transfer order
     */
    public function cancel()
    {
        $this->update([
            'status' => 'cancelled',
        ]);
    }

    /**
     * Check if TO can be approved
     */
    public function canBeApproved()
    {
        return $this->status === 'created';
    }

    /**
     * Check if TO can be executed
     */
    public function canBeExecuted()
    {
        return in_array($this->status, ['approved', 'in_progress']);
    }

    /**
     * Scope by status
     */
    public function scopeByStatus($query, $status)
    {
        return $query->where('status', $status);
    }

    /**
     * Scope for auto-generated TOs
     */
    public function scopeAutoGenerated($query)
    {
        return $query->where('auto_generated', true);
    }

    /**
     * Scope by priority
     */
    public function scopeByPriority($query, $priority)
    {
        return $query->where('priority', $priority);
    }

    /**
     * Scope by assigned operator
     */
    public function scopeAssignedTo($query, $userId)
    {
        return $query->where('assigned_to', $userId);
    }
}

